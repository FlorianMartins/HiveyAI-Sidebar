// Exported so a test can check EVERY key the UI asks for actually exists: a missing key falls back
// to English and then to the RAW KEY, which is what a user sees printed on screen.
export const DICT = { en: EN, fr: FR, es: ES, de: DE, it: IT, pt: PT };

// Any of the six dictionaries (it used to keep only "fr", so Spanish, German, Italian and
// Portuguese, offered in the settings, showed the interface in English).
export function setLang(l) {
  lang = Object.prototype.hasOwnProperty.call(DICT, l) ? l : "en";
}

export function getLang() {
  return lang;
}

// Translate `key` for the active language, falling back to English then the key
// itself. `vars` fills {name} placeholders.
export function t(key, vars) {
  const table = DICT[lang] || EN;
  let s = table[key];
  if (s == null) s = EN[key];
  if (s == null) s = key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, n) => (vars[n] != null ? vars[n] : m));
  }
  return s;
}

// Fill annotated static markup. Supported attributes:
//   data-i18n        → textContent
//   data-i18n-html   → innerHTML (for strings containing markup)
//   data-i18n-title  → title attribute
//   data-i18n-ph     → placeholder attribute
export function applyDom(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => {
    setHTML(el, t(el.getAttribute("data-i18n-html")));
  });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.title = t(el.getAttribute("data-i18n-title"));
  });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
}
